// Preserve the authoritative Graph SVG. Publish only its vector overlay beside it;
// the browser reuses the lossless plan image already loaded by the first two steps.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {parseFinalGraph}=require('./refresh-reference-graphs.cjs');
const project=path.resolve(__dirname,'..'),root=path.join(project,'data/reference-pipeline/v1');
const index=JSON.parse(fs.readFileSync(path.join(root,'index.json'),'utf8'));
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const layers={},report=[];
for(const {id} of index.cases){
  const data=JSON.parse(fs.readFileSync(path.join(root,id,'case.json'),'utf8'));
  const source=fs.readFileSync(path.join(root,id,'graph.svg')),plan=fs.readFileSync(path.join(root,id,'plan.png'));
  const parsed=parseFinalGraph(source,plan);
  if(hash(source)!==data.graphArtifact.sha256)throw Error('Graph source changed: '+id);
  const svg=source.toString('utf8'),images=[...svg.matchAll(/<image\b[^>]*\/>/g)];
  if(images.length!==1)throw Error('Expected one embedded plan: '+id);
  const overlay=svg.replace(images[0][0],'');
  if(/<image\b|data:image|<script\b/i.test(overlay))throw Error('Overlay must contain only original vector markup');
  fs.writeFileSync(path.join(root,id,'graph-overlay.svg'),overlay);
  const overlayUrl=`/assets/reference-pipeline/v1/${id}/graph-overlay.svg`;
  layers[data.graphArtifact.image]={plan:data.plan.image,overlay:overlayUrl,viewBox:parsed.viewBox,width:parsed.layout.width,height:parsed.layout.height};
  if(!index.files.includes(`${id}/graph-overlay.svg`))index.files.push(`${id}/graph-overlay.svg`);
  report.push({id,sourceBytes:source.length,overlayBytes:Buffer.byteLength(overlay),sourceSha256:hash(source),overlaySha256:hash(overlay),viewBox:parsed.viewBox,nodes:parsed.graphNodes.length,edges:parsed.graphEdges.length});
}
index.files.sort();fs.writeFileSync(path.join(root,'index.json'),JSON.stringify(index,null,2)+'\n');
fs.writeFileSync(path.join(project,'frontend/src/graph-assets.generated.js'),'// Generated by scripts/prepare-graph-layers.cjs; originals are retained.\nexport default '+JSON.stringify(layers,null,2)+';\n');
fs.writeFileSync(path.join(root,'graph-layers-report.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
