const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const project=path.resolve(__dirname,'..'),output=path.join(project,'data/web-images'),reportFile=path.join(output,'compression-report.json');
const {ImagePool}=require(path.join(project,'../.runtime/squoosh/node_modules/@squoosh/lib'));
const report=JSON.parse(fs.readFileSync(reportFile,'utf8')),pool=new ImagePool(1);
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
(async()=>{try{
  for(const row of report.images){
    if(!row.width||Math.max(row.width,row.height)<=800||/\/(masks\/|segmentation\.)/.test(row.source))continue;
    if(row.thumbnail&&fs.existsSync(path.join(output,row.thumbnail.output)))continue;
    try {
    const cachedName=row.sourceSha256.slice(0,20)+'-thumb.webp',cached=path.join(output,'files',cachedName);
    if(fs.existsSync(cached)){
      const bytes=fs.readFileSync(cached),decoded=await pool.ingestImage(bytes).decoded;
      row.thumbnail={output:'files/'+cachedName,url:'/assets/optimized/'+cachedName,bytes:bytes.length,width:decoded.bitmap.width,height:decoded.bitmap.height,sha256:hash(bytes),encoder:'webp',quality:86};
      fs.writeFileSync(reportFile,JSON.stringify(report,null,2)+'\n');continue;
    }
    const image=pool.ingestImage(fs.readFileSync(path.join(project,'frontend/public',row.source)));
    const width=Math.max(1,Math.round(row.width*Math.min(1,800/Math.max(row.width,row.height)))),height=Math.max(1,Math.round(row.height*Math.min(1,800/Math.max(row.width,row.height))));
    await image.preprocess({resize:{width,height}});await image.encode({webp:{quality:86,method:6,alpha_quality:100,exact:1,use_sharp_yuv:1}});
    const bytes=image.encodedWith.webp.binary,decoded=await pool.ingestImage(bytes).decoded;
    if(decoded.bitmap.width!==width||decoded.bitmap.height!==height)throw Error('Thumbnail dimensions mismatch');
    if(bytes.length<row.bytes*.85){
      const name=row.sourceSha256.slice(0,20)+'-thumb.webp';fs.writeFileSync(path.join(output,'files',name),bytes);
      row.thumbnail={output:'files/'+name,url:'/assets/optimized/'+name,bytes:bytes.length,width,height,sha256:hash(bytes),encoder:'webp',quality:86};
    }
    }catch(error){row.thumbnailError=String(error?.message||error);console.log(JSON.stringify({thumbnailFallback:row.source,reason:row.thumbnailError}));}
    fs.writeFileSync(reportFile,JSON.stringify(report,null,2)+'\n');
  }
  const map=Object.fromEntries(report.images.filter(row=>row.output||row.thumbnail).map(row=>[row.source,{url:row.url||row.source,lossless:row.lossless,width:row.width,height:row.height,...(row.thumbnail?{thumbnail:row.thumbnail.url}:{})}]));
  const publicOut=path.join(project,'frontend/public/assets/optimized');fs.mkdirSync(publicOut,{recursive:true});
  for(const row of report.images)for(const file of [row.output,row.thumbnail?.output].filter(Boolean))fs.copyFileSync(path.join(output,file),path.join(publicOut,path.basename(file)));
  fs.writeFileSync(reportFile,JSON.stringify(report,null,2)+'\n');
  fs.writeFileSync(path.join(project,'frontend/src/image-assets.generated.json'),JSON.stringify(map,null,2)+'\n');
  fs.writeFileSync(path.join(project,'frontend/src/image-assets.generated.js'),'// Generated by Squoosh asset preparation.\nexport default '+JSON.stringify(map,null,2)+';\n');
  console.log(JSON.stringify({status:'passed',thumbnails:report.images.filter(row=>row.thumbnail).length,sourceCardBytes:report.images.filter(row=>row.source.startsWith('/assets/reference-sources/')).reduce((n,row)=>n+(row.thumbnail?.bytes||row.bytes),0)}));
}finally{await pool.close();}})().catch(error=>{console.error(error);process.exitCode=1;});
